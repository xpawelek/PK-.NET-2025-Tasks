namespace dotnet_lab3_scientific_calculator;

public class ScientificCalculator
{ 
    public double Power(double a, double b)
    {
        return Math.Pow(a, b);
    }

    public double SquareRoot(double a)
    {
        return Math.Sqrt(a);
    }

    public double Log(double a)
    {
        return Math.Log(a);
    }
}